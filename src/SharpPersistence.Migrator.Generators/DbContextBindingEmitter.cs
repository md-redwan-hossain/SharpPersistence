using System.Text;

namespace SharpPersistence.Migrator.Generators;

internal static class DbContextBindingEmitter
{
    public static string Emit(DbContextBindingModel model)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using Microsoft.EntityFrameworkCore;");
        sb.AppendLine("using SharpPersistence.Migrator.EfCore;");
        sb.AppendLine();

        if (!string.IsNullOrWhiteSpace(model.Namespace))
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        var indent = string.Empty;
        foreach (var containing in model.ContainingTypeDeclarations)
        {
            sb.AppendLine($"{indent}{containing}");
            sb.AppendLine($"{indent}{{");
            indent += "    ";
        }

        sb.AppendLine($"{indent}partial class {model.SimpleName}");
        sb.AppendLine($"{indent}{{");
        var memberIndent = indent + "    ";

        var needsSeparator = false;

        if (model.GenerateOnModelCreating && model.BoundEntityTypeNames.Length > 0)
        {
            sb.AppendLine($"{memberIndent}private static readonly global::System.Type[] _sharpPersistenceBoundEntityTypes =");
            sb.AppendLine($"{memberIndent}[");
            for (var i = 0; i < model.BoundEntityTypeNames.Length; i++)
            {
                var comma = i + 1 < model.BoundEntityTypeNames.Length ? "," : string.Empty;
                sb.AppendLine($"{memberIndent}    typeof({model.BoundEntityTypeNames[i]}){comma}");
            }

            sb.AppendLine($"{memberIndent}];");
            needsSeparator = true;
        }

        if (model.GenerateConstructor)
        {
            if (needsSeparator)
            {
                sb.AppendLine();
            }

            sb.AppendLine($"{memberIndent}private readonly global::{GeneratorConstants.DatabaseModelMetadataName} _sharpPersistenceSchema;");
            sb.AppendLine();
            sb.AppendLine($"{memberIndent}public {model.SimpleName}(");
            sb.AppendLine($"{memberIndent}    DbContextOptions<{model.SimpleName}> options,");
            sb.AppendLine($"{memberIndent}    global::{GeneratorConstants.DatabaseModelMetadataName} schema)");
            sb.AppendLine($"{memberIndent}    : base(options)");
            sb.AppendLine($"{memberIndent}{{");
            sb.AppendLine($"{memberIndent}    _sharpPersistenceSchema = schema;");
            sb.AppendLine($"{memberIndent}}}");
            needsSeparator = true;
        }

        if (model.Properties.Length > 0)
        {
            if (needsSeparator)
            {
                sb.AppendLine();
            }

            foreach (var prop in model.Properties)
            {
                if (prop.IsReadOnly)
                {
                    sb.AppendLine(
                        $"{memberIndent}public IQueryable<{prop.EntityFullTypeName}> {prop.PropertyName} => Set<{prop.EntityFullTypeName}>().AsNoTracking();");
                }
                else
                {
                    sb.AppendLine(
                        $"{memberIndent}public DbSet<{prop.EntityFullTypeName}> {prop.PropertyName} => Set<{prop.EntityFullTypeName}>();");
                }
            }

            needsSeparator = true;
        }

        if (model.GenerateOnModelCreating)
        {
            if (needsSeparator)
            {
                sb.AppendLine();
            }

            var schemaRef = model.GenerateConstructor
                ? "_sharpPersistenceSchema"
                : model.ExistingSchemaMemberName!;

            sb.AppendLine($"{memberIndent}protected override void OnModelCreating(ModelBuilder modelBuilder)");
            sb.AppendLine($"{memberIndent}{{");
            sb.AppendLine($"{memberIndent}    base.OnModelCreating(modelBuilder);");
            if (model.BoundEntityTypeNames.Length > 0)
            {
                sb.AppendLine($"{memberIndent}    modelBuilder.ApplySchemaToEfCore({schemaRef}, _sharpPersistenceBoundEntityTypes);");
            }
            else
            {
                sb.AppendLine($"{memberIndent}    modelBuilder.ApplySchemaToEfCore({schemaRef});");
            }

            sb.AppendLine($"{memberIndent}    OnModelCreatingPartial(modelBuilder);");
            sb.AppendLine($"{memberIndent}}}");
            sb.AppendLine();
            sb.AppendLine($"{memberIndent}partial void OnModelCreatingPartial(ModelBuilder modelBuilder);");
        }

        sb.AppendLine($"{indent}}}");

        for (var i = model.ContainingTypeDeclarations.Length - 1; i >= 0; i--)
        {
            indent = indent.Substring(0, indent.Length - 4);
            sb.AppendLine($"{indent}}}");
        }

        return sb.ToString();
    }
}
