using SharpPersistence.Enums;
using SharpPersistence.Migrator.Configuration;
using SharpPersistence.Migrator.Dialects;
using SharpPersistence.Migrator.Diffing;
using SharpPersistence.Migrator.Enums;
using SharpPersistence.Migrator.Models;

namespace SharpPersistence.Migrator.Tests;

public sealed class OracleDialectGeneratorTests
{
    [Fact]
    public void GenerateSql_Oracle19_UsesUserTablesAndAllSequencesCatalogGuards()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.Oracle19);
        var ops = new SchemaOperation[]
        {
            new CreateSequenceOp(new SequenceSchema { Name = "SEQ_ORDERS", Schema = "APP", StartValue = 100, IncrementBy = 1 }),
            new CreateTableOp(new TableSchema
            {
                EntityName = "Order",
                TableName = "ORDERS",
                PrimaryKey = new PrimaryKeySchema { Name = "PK_ORDERS", ColumnNames = ["ID"], PropertyNames = ["Id"] },
                Columns =
                [
                    new ColumnSchema { PropertyName = "Id", ColumnName = "ID", SqlType = "NUMBER(19)", IsNullable = false, IsIdentity = true },
                    new ColumnSchema { PropertyName = "Code", ColumnName = "CODE", SqlType = "VARCHAR2(32)", IsNullable = false }
                ]
            })
        };

        var sql = generator.GenerateSql(ops);

        Assert.Contains("ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'APP' AND SEQUENCE_NAME = 'SEQ_ORDERS'", sql);
        Assert.Contains("FROM USER_TABLES WHERE TABLE_NAME = 'ORDERS'", sql);
        Assert.Contains("GENERATED BY DEFAULT ON NULL AS IDENTITY", sql);
        Assert.DoesNotContain("BEGIN;", sql);
    }

    [Fact]
    public void GenerateSql_Oracle23_DropColumnAndConstraint_DoNotEmitAlterTableIfExists()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.Oracle23);
        var sql = generator.GenerateSql([
            new DropColumnOp("APP", "ORDERS", "OLD_COL"),
            new DropForeignKeyOp("APP", "ORDERS", "FK_OLD")
        ]);

        Assert.DoesNotContain("ALTER TABLE IF EXISTS", sql);
        Assert.Contains("ALTER TABLE \"APP\".\"ORDERS\" DROP COLUMN IF EXISTS \"OLD_COL\";", sql);
        Assert.Contains("ALL_CONSTRAINTS WHERE OWNER = 'APP' AND TABLE_NAME = 'ORDERS' AND CONSTRAINT_NAME = 'FK_OLD'", sql);
        Assert.Contains("ALTER TABLE \"APP\".\"ORDERS\" DROP CONSTRAINT \"FK_OLD\"", sql);
    }

    [Fact]
    public void GenerateSql_AlterColumn_OnlyEmitsNullabilityWhenChanged()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.Oracle19);
        var oldCol = new ColumnSchema { ColumnName = "NAME", SqlType = "VARCHAR2(50)", IsNullable = false };
        var newCol = new ColumnSchema { ColumnName = "NAME", SqlType = "VARCHAR2(100)", IsNullable = false };

        var sql = generator.GenerateSql([new AlterColumnOp(null, "USERS", oldCol, newCol)]);

        Assert.Contains("MODIFY (\"NAME\" VARCHAR2(100))", sql);
        Assert.DoesNotContain("NOT NULL", sql);
    }

    [Fact]
    public void GenerateSql_BooleanDefault_NormalizesTrueFalseToOneZeroOnNumber1()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.OracleDb19);
        var addCol = new AddColumnOp(null, "USERS", new ColumnSchema
        {
            ColumnName = "IS_ACTIVE",
            SqlType = "NUMBER(1)",
            IsNullable = false,
            DefaultValueSql = "TRUE"
        });

        var sql = generator.GenerateSql([addCol]);

        Assert.Contains("DEFAULT 1 NOT NULL", sql);
        Assert.DoesNotContain("DEFAULT TRUE", sql);
    }

    [Fact]
    public void GenerateSql_CreateTable_DoesNotDuplicateCommentsOrInlineFks()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.OracleDb23);
        var table = new TableSchema
        {
            TableName = "ORDERS",
            Comment = "Order header",
            Columns = [new ColumnSchema { ColumnName = "ID", SqlType = "RAW(16)", IsNullable = false, Comment = "Primary key" }],
            ForeignKeys = [new ForeignKeySchema { Name = "FK_ORDERS_USERS", DependentColumns = ["USER_ID"], PrincipalTable = "USERS", PrincipalColumns = ["ID"] }]
        };

        var sql = generator.GenerateSql([
            new CreateTableOp(table),
            new SetTableCommentOp(null, "ORDERS", "Order header"),
            new SetColumnCommentOp(null, "ORDERS", "ID", "Primary key")
        ]);

        Assert.DoesNotContain("FK_ORDERS_USERS", sql);
        Assert.Equal(1, sql.Split("COMMENT ON TABLE").Length - 1);
        Assert.Equal(1, sql.Split("COMMENT ON COLUMN").Length - 1);
    }

    [Fact]
    public void GenerateSql_AlterColumn_HandlesIdentityAndComputedChanges()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.OracleDb19);
        var oldIdentity = new ColumnSchema { ColumnName = "ID", SqlType = "NUMBER(19)", IsNullable = false, IsIdentity = false };
        var newIdentity = new ColumnSchema { ColumnName = "ID", SqlType = "NUMBER(19)", IsNullable = false, IsIdentity = true };

        var idSql = generator.GenerateSql([new AlterColumnOp(null, "USERS", oldIdentity, newIdentity)]);
        Assert.Contains("MODIFY (\"ID\" GENERATED BY DEFAULT ON NULL AS IDENTITY)", idSql);

        var dropIdSql = generator.GenerateSql([new AlterColumnOp(null, "USERS", newIdentity, oldIdentity)]);
        Assert.Contains("MODIFY (\"ID\" DROP IDENTITY)", dropIdSql);

        var oldComputed = new ColumnSchema { ColumnName = "TOTAL", SqlType = "NUMBER(18,2)", IsNullable = false, ComputedColumnSql = "\"A\" + \"B\"" };
        var newComputed = new ColumnSchema { ColumnName = "TOTAL", SqlType = "NUMBER(18,2)", IsNullable = false, ComputedColumnSql = "\"A\" + \"B\" + \"C\"" };
        var compSql = generator.GenerateSql([new AlterColumnOp(null, "USERS", oldComputed, newComputed)]);
        Assert.Contains("DROP COLUMN \"TOTAL\"", compSql);
        Assert.Contains("GENERATED ALWAYS AS (\"A\" + \"B\" + \"C\") VIRTUAL", compSql);
    }

    [Fact]
    public void GenerateSql_RenameTableAcrossSchemas_ThrowsNotSupportedException()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.OracleDb19);
        Assert.Throws<NotSupportedException>(() =>
            generator.GenerateSql([new RenameTableOp("OLD_SCHEMA", "ORDERS", "NEW_SCHEMA", "ORDERS")]));
    }

    [Fact]
    public void GenerateSql_PostgresStorageOperations_ThrowNotSupportedException()
    {
        var generator = new OracleDialectGenerator(OracleDbCompatibility.OracleDb19);
        SchemaOperation[] unsupportedOps =
        [
            new SetTableLoggedOp(null, "ORDERS", IsUnlogged: true),
            new SetTableTablespaceOp(null, "ORDERS", "FAST_SSD"),
            new AlterTableStorageParametersOp(null, "ORDERS", new Dictionary<string, string> { ["fillfactor"] = "80" }, []),
            new SetIndexTablespaceOp(null, "IX_ORDERS_CODE", "IDX_DISK"),
            new AlterIndexStorageParametersOp(null, "IX_ORDERS_CODE", new Dictionary<string, string> { ["fillfactor"] = "70" }, [])
        ];

        foreach (var op in unsupportedOps)
        {
            Assert.Throws<NotSupportedException>(() => generator.GenerateSql([op]));
        }
    }

    [Fact]
    public void UseOracle_CallbackOverload_PreservesFluentChainAndConfiguresCompatibility()
    {
        var options = new MigrationManagerOptionsBuilder()
            .UseOracle("Data Source=localhost/XEPDB1", oracle => oracle
                .UseSqlCompatibility(OracleDbCompatibility.OracleDb23))
            .UseNamingConvention(SqlIdentifierCase.UpperSnakeCase)
            .UseMigrationsDirectory("db/oracle_migrations")
            .Build();

        Assert.Equal(SqlDialect.Oracle, options.Dialect);
        Assert.Equal(OracleDbCompatibility.OracleDb23, options.OracleCompatibility);
        Assert.Equal("db/oracle_migrations", options.MigrationsDirectory);
    }
}
